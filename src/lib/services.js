export function slugify(name) {
  return name
    .toLowerCase()
    .replace(/®/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

export function getAllServicesFlat() {
  return SERVICE_CATEGORIES.flatMap((category) =>
    category.items.map((item) => ({
      ...item,
      category: category.name,
      slug: slugify(item.name),
    }))
  );
}

export function getServiceBySlug(slug) {
  return getAllServicesFlat().find((item) => item.slug === slug);
}

export function priceToNumber(priceString) {
  return Number(priceString.replace(/[₦,]/g, ""));
}